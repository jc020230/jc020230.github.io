/** Update static SEO from data.js: node tools/sync-meta.mjs [--check]. No dependencies. */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const context = { window: {} };
for (const name of ["data", "i18n"]) {
  vm.runInNewContext(fs.readFileSync(path.join(root, `assets/js/${name}.js`), "utf8"), context, { timeout: 1000 });
}
const data = context.window.SITE_DATA;
const lang = data.site.defaultLanguage;
const local = (value) => typeof value === "object" ? value?.[lang] ?? value?.en ?? value?.ko ?? "" : value ?? "";
const escape = (value) => String(value).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const base = new URL(data.site.url);
if (base.protocol !== "https:" || base.search || base.hash || !base.pathname.endsWith("/")) {
  throw new Error("site.url must be an HTTPS URL ending in /, without a query or hash.");
}
const examples = data.site.showDemoNotice || data.profile.example ||
  ["news", "publications", "projects", "education", "experience", "awards"].some((key) => data[key]?.some((item) => item.example));
let stale = false;
function output(filename, content) {
  const target = path.join(root, filename);
  const previous = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (previous === content) return;
  if (process.argv.includes("--check")) { console.error(`STALE: ${filename}; run node tools/sync-meta.mjs`); stale = true; }
  else { fs.writeFileSync(target, content); console.log(`Updated ${filename}`); }
}
for (const filename of ["index.html", "cv.html"]) {
  const url = new URL(filename === "index.html" ? "./" : filename, base).href;
  const title = `${local(data.profile.name)} | ${filename === "cv.html" ? context.window.SITE_I18N[lang].cvTitle : local(data.site.title)}`;
  const meta = `<!-- site-meta:start (generated by tools/sync-meta.mjs) -->
  <title>${escape(title)}</title>
  <meta name="description" content="${escape(local(data.site.description))}">
  <meta name="robots" content="${examples ? "noindex, nofollow" : "index, follow"}">
  <link rel="canonical" href="${escape(url)}">
  <meta property="og:type" content="website">
  <meta property="og:title" content="${escape(title)}">
  <meta property="og:description" content="${escape(local(data.site.description))}">
  <meta property="og:url" content="${escape(url)}">
  <meta property="og:locale" content="${lang === "ko" ? "ko_KR" : "en_US"}">
  <!-- site-meta:end -->`;
  const html = fs.readFileSync(path.join(root, filename), "utf8");
  if (!html.includes("<!-- site-meta:start")) throw new Error(`Missing metadata markers: ${filename}`);
  output(filename, html.replace(/<!-- site-meta:start[\s\S]*?<!-- site-meta:end -->/, meta).replace(/<html lang="[^"]+">/, `<html lang="${lang}">`));
}
output("robots.txt", `User-agent: *\nAllow: /\n\nSitemap: ${new URL("sitemap.xml", base).href}\n`);
output("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${["./", "cv.html"].map((p) => `  <url><loc>${escape(new URL(p, base).href)}</loc><lastmod>${escape(data.site.updated)}</lastmod></url>`).join("\n")}
</urlset>
`);
if (stale) process.exit(1);
console.log(process.argv.includes("--check") ? "PASS: static metadata matches data.js." : "Metadata synchronized. The site remains buildless.");
